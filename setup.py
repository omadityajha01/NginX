#!/usr/bin/env python3
"""
NGINX server generator.

You provide 5 inputs (domain, listen ports, backend IP(s), backend port(s),
backend protocol). This script generates a complete NGINX setup with load
balancing, caching, HTTPS, security headers, rate limiting and logging,
then starts it in Docker.

Usage:
    python setup.py               # interactive prompts (defaults = last run)
    python setup.py --from-file   # regenerate from nginx-inputs.json, no prompts
    python setup.py --no-start    # only generate files, don't touch Docker

Standard library only. Requires Docker Desktop for running.
"""

import argparse
import ipaddress
import json
import re
import shutil
import socket
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TEMPLATES_DIR = ROOT / "templates"
INPUTS_FILE = ROOT / "nginx-inputs.json"
NGINX_DIR = ROOT / "nginx"
CERTS_DIR = ROOT / "certs"
COMPOSE_FILE = ROOT / "docker-compose.yml"

NGINX_IMAGE = "nginx:1.27-alpine"
DEMO_IMAGE = "traefik/whoami:v1.10"
DEMO_APPS = ["app1", "app2", "app3"]
DEMO_BACKENDS = [f"{name}:80" for name in DEMO_APPS]

PROTOCOLS = {
    "http": "plain HTTP app (Node, Python, Java, Go, ...)",
    "https": "app that itself speaks HTTPS",
    "fastcgi": "PHP-FPM / FastCGI",
    "grpc": "gRPC service",
}

# Inside a container, these addresses mean the container itself, not your PC.
LOCAL_ALIASES = {"localhost", "127.0.0.1", "::1", "0.0.0.0"}
HOST_GATEWAY = "host.docker.internal"

GENERATED_NOTE = (
    "# GENERATED by setup.py - do not edit by hand.\n"
    "# Change nginx-inputs.json (then: python setup.py --from-file) or templates/."
)

HOSTNAME_RE = re.compile(
    r"^(?=.{1,253}$)(?!-)[A-Za-z0-9-]{1,63}(?<!-)(\.(?!-)[A-Za-z0-9-]{1,63}(?<!-))*$"
)


# --------------------------------------------------------------------------- #
# Validation helpers
# --------------------------------------------------------------------------- #

def is_ip(value: str) -> bool:
    try:
        ipaddress.ip_address(value)
        return True
    except ValueError:
        return False


def is_valid_host(value: str) -> bool:
    return is_ip(value) or bool(HOSTNAME_RE.match(value))


def parse_port(value) -> int:
    try:
        port = int(str(value).strip())
    except ValueError:
        raise ValueError(f"'{value}' is not a number")
    if not 1 <= port <= 65535:
        raise ValueError(f"port {port} must be between 1 and 65535")
    return port


def parse_domains(value: str) -> list:
    domains = value.replace(",", " ").split()
    if not domains:
        raise ValueError("at least one domain is required")
    for d in domains:
        if not is_valid_host(d):
            raise ValueError(f"'{d}' is not a valid domain name or IP")
    return domains


def parse_backend(text: str):
    """Parse 'host:port', '[ipv6]:port' or 'scheme://host:port'.

    Returns (host, port, scheme_or_None).
    """
    text = text.strip().rstrip("/")
    scheme = None
    m = re.match(r"^([a-zA-Z]+)://(.*)$", text)
    if m:
        scheme, text = m.group(1).lower(), m.group(2)
        if scheme not in PROTOCOLS:
            raise ValueError(f"unknown scheme '{scheme}://'")

    m = re.match(r"^\[([0-9a-fA-F:.]+)\]:(\d+)$", text) or re.match(r"^([^:\[\]]+):(\d+)$", text)
    if not m:
        raise ValueError(f"'{text}' must look like IP:PORT or HOSTNAME:PORT (e.g. 10.0.0.5:3000)")
    host, port = m.group(1), parse_port(m.group(2))
    if not is_valid_host(host):
        raise ValueError(f"'{host}' is not a valid IP address or hostname")
    return host, port, scheme


def format_backend(host: str, port: int) -> str:
    if is_ip(host) and ipaddress.ip_address(host).version == 6:
        return f"[{host}]:{port}"
    return f"{host}:{port}"


def rewrite_local(host: str) -> str:
    if host.lower() in LOCAL_ALIASES:
        print(f"    note: '{host}' inside Docker means the NGINX container itself;"
              f" using '{HOST_GATEWAY}' (= this PC) instead.")
        return HOST_GATEWAY
    return host


def validate_inputs(raw: dict) -> dict:
    """Normalise and validate inputs (used for both prompts and --from-file)."""
    demo = bool(raw.get("demo", False))
    inputs = {
        "domain": " ".join(parse_domains(str(raw.get("domain", "localhost")))),
        "http_port": parse_port(raw.get("http_port", 80)),
        "https_port": parse_port(raw.get("https_port", 443)),
        "demo": demo,
    }
    if inputs["http_port"] == inputs["https_port"]:
        raise ValueError("HTTP and HTTPS ports must be different")

    if demo:
        inputs["backends"] = list(DEMO_BACKENDS)
        inputs["protocol"] = "http"
    else:
        protocol = str(raw.get("protocol", "http")).lower()
        if protocol not in PROTOCOLS:
            raise ValueError(f"protocol must be one of: {', '.join(PROTOCOLS)}")
        backends = raw.get("backends") or []
        if not backends:
            raise ValueError("at least one backend is required (or set \"demo\": true)")
        normalised = []
        for b in backends:
            host, port, _ = parse_backend(str(b))
            normalised.append(format_backend(rewrite_local(host), port))
        inputs["backends"] = normalised
        inputs["protocol"] = protocol
        if protocol == "fastcgi":
            inputs["fastcgi_root"] = str(raw.get("fastcgi_root", "/var/www/html")).rstrip("/") or "/"
    return inputs


# --------------------------------------------------------------------------- #
# Interactive prompts
# --------------------------------------------------------------------------- #

def ask(question: str, default=None) -> str:
    suffix = f" [{default}]" if default not in (None, "") else ""
    answer = input(f"{question}{suffix}: ").strip()
    return answer if answer else ("" if default is None else str(default))


def ask_until_valid(question, default, parser):
    while True:
        value = ask(question, default)
        try:
            return parser(value)
        except ValueError as exc:
            print(f"    ! {exc}")


def port_in_use(port: int) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        try:
            s.bind(("0.0.0.0", port))
            return False
        except OSError:
            return True


def ask_port(label: str, default: int, alternative: int, skip_check: bool) -> int:
    while True:
        port = ask_until_valid(f"{label} listen port", default, parse_port)
        if skip_check or not port_in_use(port):
            return port
        print(f"    ! port {port} is already in use on this PC (try {alternative}).")
        default = alternative


def prompt_inputs(previous: dict, nginx_running: bool) -> dict:
    print("\n=== NGINX server setup ===  (press Enter to accept the [default])\n")

    print("1) Domain name(s) - separate several with spaces")
    domain = ask_until_valid("   Domain", previous.get("domain", "localhost"),
                             lambda v: " ".join(parse_domains(v)))

    print("\n2) Ports on this PC that NGINX will listen on")
    if nginx_running:
        print("   (this NGINX is already running, so the port-in-use check is skipped)")
    http_port = ask_port("   HTTP ", previous.get("http_port", 80), 8080, nginx_running)
    while True:
        https_port = ask_port("   HTTPS", previous.get("https_port", 443), 8443, nginx_running)
        if https_port != http_port:
            break
        print("    ! HTTPS port must differ from the HTTP port.")

    print("\n3) Backend servers - one IP:PORT per line, empty line to finish")
    print("   Press Enter on the first line to use 3 built-in DEMO backends.")
    backends, detected_scheme = [], None
    while True:
        line = input(f"   Backend {len(backends) + 1}: ").strip()
        if not line:
            break
        try:
            host, port, scheme = parse_backend(line)
        except ValueError as exc:
            print(f"    ! {exc}")
            continue
        detected_scheme = detected_scheme or scheme
        entry = format_backend(rewrite_local(host), port)
        if entry in backends:
            print("    ! already added")
            continue
        backends.append(entry)

    if not backends:
        print("   -> using demo backends: " + ", ".join(DEMO_BACKENDS))
        return validate_inputs({"domain": domain, "http_port": http_port,
                                "https_port": https_port, "demo": True})

    print("\n4) Backend protocol")
    for name, desc in PROTOCOLS.items():
        print(f"   - {name:8} {desc}")
    default_proto = detected_scheme or (previous.get("protocol") if not previous.get("demo") else None) or "http"

    def parse_proto(v):
        v = v.lower()
        if v not in PROTOCOLS:
            raise ValueError(f"choose one of: {', '.join(PROTOCOLS)}")
        return v

    protocol = ask_until_valid("   Protocol", default_proto, parse_proto)

    raw = {"domain": domain, "http_port": http_port, "https_port": https_port,
           "demo": False, "backends": backends, "protocol": protocol}
    if protocol == "fastcgi":
        raw["fastcgi_root"] = ask("   Document root on the PHP server",
                                  previous.get("fastcgi_root", "/var/www/html"))
    # Backends are already rewritten; validate again without re-printing notes.
    return validate_inputs(raw)


# --------------------------------------------------------------------------- #
# Config generation
# --------------------------------------------------------------------------- #

def render(template_name: str, values: dict) -> str:
    text = (TEMPLATES_DIR / template_name).read_text(encoding="utf-8")
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", value)
    leftover = re.findall(r"\{\{[A-Z_]+\}\}", text)
    if leftover:
        raise RuntimeError(f"{template_name}: unfilled placeholders {sorted(set(leftover))}")
    return text


def proxy_block(inputs: dict) -> str:
    scheme = "https" if inputs["protocol"] == "https" else "http"
    lines = [
        f"proxy_pass {scheme}://app_backend;",
        "proxy_http_version 1.1;",
        "",
        "# Tell the app who the real client is",
        "proxy_set_header Host              $host;",
        "proxy_set_header X-Real-IP         $remote_addr;",
        "proxy_set_header X-Forwarded-For   $proxy_add_x_forwarded_for;",
        "proxy_set_header X-Forwarded-Proto $scheme;",
        "proxy_set_header X-Forwarded-Host  $host;",
        "",
        "# WebSockets + upstream keepalive",
        "proxy_set_header Upgrade    $http_upgrade;",
        "proxy_set_header Connection $connection_upgrade;",
        "",
        "# Timeouts and automatic retry on another backend",
        "proxy_connect_timeout 5s;",
        "proxy_send_timeout    60s;",
        "proxy_read_timeout    60s;",
        "proxy_next_upstream error timeout http_502 http_503;",
        "proxy_next_upstream_tries 3;",
        "",
        "# Caching (only when the backend sends Cache-Control; never for logged-in users)",
        "proxy_cache app_cache;",
        "proxy_cache_bypass $skip_cache;",
        "proxy_no_cache     $skip_cache;",
        "proxy_cache_use_stale error timeout updating http_500 http_502 http_503 http_504;",
        "proxy_cache_lock on;",
        "proxy_cache_background_update on;",
    ]
    if scheme == "https":
        first_host = inputs["backends"][0].rsplit(":", 1)[0].strip("[]")
        lines += [
            "",
            "# Backend speaks HTTPS",
            "proxy_ssl_server_name on;",
            f"proxy_ssl_name {first_host};",
            "proxy_ssl_session_reuse on;",
        ]
    return lines


def fastcgi_block(inputs: dict) -> list:
    return [
        "include fastcgi_params;",
        "fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;",
        "fastcgi_param HTTPS on;",
        "fastcgi_index index.php;",
        "fastcgi_pass app_backend;",
        "fastcgi_keep_conn on;           # needed for upstream keepalive",
        "",
        "fastcgi_connect_timeout 5s;",
        "fastcgi_read_timeout    60s;",
        "fastcgi_next_upstream error timeout;",
    ]


def grpc_block(inputs: dict) -> list:
    return [
        "grpc_pass grpc://app_backend;",
        "grpc_set_header X-Real-IP       $remote_addr;",
        "grpc_set_header X-Forwarded-For $proxy_add_x_forwarded_for;",
        "",
        "grpc_connect_timeout 5s;",
        "grpc_read_timeout    60s;",
        "grpc_next_upstream error timeout http_502 http_503;",
    ]


def build_site_conf(inputs: dict) -> str:
    builders = {"http": proxy_block, "https": proxy_block,
                "fastcgi": fastcgi_block, "grpc": grpc_block}
    block = builders[inputs["protocol"]](inputs)
    indent = " " * 8
    protocol_block = "\n".join(indent + line if line else "" for line in block)

    upstream = "\n".join(
        f"    server {b} max_fails=3 fail_timeout=30s;" for b in inputs["backends"]
    )
    server_extra = ""
    if inputs["protocol"] == "fastcgi":
        server_extra = f"\n    root {inputs['fastcgi_root']};       # document root on the PHP server\n"

    https_port = inputs["https_port"]
    return render("site.conf.tmpl", {
        "GENERATED_NOTE": GENERATED_NOTE,
        "DOMAIN": inputs["domain"],
        "PROTOCOL": inputs["protocol"],
        "UPSTREAM_SERVERS": upstream,
        "HTTPS_PORT_SUFFIX": "" if https_port == 443 else f":{https_port}",
        "SERVER_EXTRA": server_extra,
        "PROTOCOL_BLOCK": protocol_block,
    })


def build_compose(inputs: dict) -> str:
    lines = [
        GENERATED_NOTE,
        "",
        "name: nginx-gateway",
        "",
        "services:",
        "  nginx:",
        f"    image: {NGINX_IMAGE}",
        "    ports:",
        f'      - "{inputs["http_port"]}:80"',
        f'      - "{inputs["https_port"]}:443"',
        "    volumes:",
        "      - ./nginx/nginx.conf:/etc/nginx/nginx.conf:ro",
        "      - ./nginx/conf.d:/etc/nginx/conf.d:ro",
        "      - ./certs:/etc/nginx/certs:ro",
        "      - nginx_cache:/var/cache/nginx/app",
        "    extra_hosts:",
        f'      - "{HOST_GATEWAY}:host-gateway"',
        "    restart: unless-stopped",
    ]
    if inputs["demo"]:
        lines.append("    depends_on:")
        lines += [f"      - {name}" for name in DEMO_APPS]
        for name in DEMO_APPS:
            lines += [
                "",
                f"  {name}:                      # demo backend: replies with its own hostname",
                f"    image: {DEMO_IMAGE}",
                f"    hostname: {name}",
                "    restart: unless-stopped",
            ]
    lines += ["", "volumes:", "  nginx_cache:", ""]
    return "\n".join(lines)


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"  wrote {path.relative_to(ROOT)}")


