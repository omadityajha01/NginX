# Main
# --------------------------------------------------------------------------- #

def main() -> int:
    sys.stdout.reconfigure(line_buffering=True)  # keep our output ordered with Docker's
    parser = argparse.ArgumentParser(description="Generate and run an NGINX server from 5 inputs.")
    parser.add_argument("--from-file", action="store_true",
                        help="use nginx-inputs.json instead of prompting")
    parser.add_argument("--no-start", action="store_true",
                        help="only generate files; don't start Docker")
    args = parser.parse_args()

    previous = {}
    if INPUTS_FILE.exists():
        try:
            previous = json.loads(INPUTS_FILE.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            if args.from_file:
                print(f"! {INPUTS_FILE.name} is not valid JSON: {exc}")
                return 1

    try:
        if args.from_file:
            if not previous:
                print(f"! {INPUTS_FILE.name} not found - run 'python setup.py' first.")
                return 1
            inputs = validate_inputs(previous)
        else:
            inputs = prompt_inputs(previous, nginx_container_running())
    except ValueError as exc:
        print(f"! Invalid input: {exc}")
        return 1

    print("\nGenerating files...")
    write(INPUTS_FILE, json.dumps(inputs, indent=2) + "\n")
    write(NGINX_DIR / "nginx.conf", render("nginx.conf.tmpl", {"GENERATED_NOTE": GENERATED_NOTE}))
    write(NGINX_DIR / "conf.d" / "site.conf", build_site_conf(inputs))
    write(COMPOSE_FILE, build_compose(inputs))

    if args.no_start:
        try:
            ensure_certificate(inputs)
        except RuntimeError as exc:
            print(f"! {exc}")
        print_summary(inputs, started=False)
        return 0

    if not docker_available():
        print("\n! Docker is not running. Start Docker Desktop, then run:"
              "  python setup.py --from-file")
        return 1

    try:
        ensure_certificate(inputs)
    except RuntimeError as exc:
        print(f"! {exc}")
        return 1

    started = start_stack()
    print_summary(inputs, started)
    return 0 if started else 1


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        print("\nCancelled.")
        sys.exit(130)
