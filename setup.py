# Self-signed certificate
# --------------------------------------------------------------------------- #

def find_openssl():
    candidates = []
    found = shutil.which("openssl")
    if found:
        candidates.append(Path(found))
    git = shutil.which("git")
    if git:
        git_root = Path(git).resolve().parent.parent  # .../Git/cmd/git.exe -> .../Git
        candidates += [git_root / "usr/bin/openssl.exe", git_root / "mingw64/bin/openssl.exe"]
    candidates += [Path(r"C:\Program Files\Git\usr\bin\openssl.exe"),
                   Path(r"C:\Program Files\Git\mingw64\bin\openssl.exe")]
    for c in candidates:
        if c.exists():
            return str(c)
    return None


def openssl_config(domains: list) -> str:
    names = list(domains)
    for extra in ("localhost", "127.0.0.1"):
        if extra not in names:
            names.append(extra)
    san = ",".join(("IP:" if is_ip(n) else "DNS:") + n for n in names)
    return (
        "[req]\nprompt = no\ndistinguished_name = dn\nx509_extensions = v3\n\n"
        f"[dn]\nCN = {domains[0]}\nO = Local NGINX (self-signed)\n\n"
        f"[v3]\nsubjectAltName = {san}\nbasicConstraints = critical,CA:false\n"
        "keyUsage = critical,digitalSignature,keyEncipherment\n"
        "extendedKeyUsage = serverAuth\n"
    )


def ensure_certificate(inputs: dict) -> None:
    domains = inputs["domain"].split()
    crt, key, marker = CERTS_DIR / "server.crt", CERTS_DIR / "server.key", CERTS_DIR / ".domains"
    if crt.exists() and key.exists() and marker.exists() and marker.read_text().strip() == inputs["domain"]:
        print("  certificate: keeping existing certs/server.crt")
        return

    CERTS_DIR.mkdir(exist_ok=True)
    cfg = CERTS_DIR / "openssl.cnf"
    cfg.write_text(openssl_config(domains), encoding="utf-8", newline="\n")
    args = ["req", "-x509", "-newkey", "rsa:2048", "-nodes", "-days", "825"]
    try:
        openssl = find_openssl()
        if openssl:
            cmd = [openssl, *args, "-keyout", key.as_posix(), "-out", crt.as_posix(),
                   "-config", cfg.as_posix()]
        else:
            print("  openssl not found locally - generating the certificate with Docker")
            inner = ("apk add --no-cache openssl >/dev/null && openssl " + " ".join(args) +
                     " -keyout /certs/server.key -out /certs/server.crt -config /certs/openssl.cnf")
            cmd = ["docker", "run", "--rm", "-v", f"{CERTS_DIR}:/certs", "alpine:3.20", "sh", "-c", inner]
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0 or not crt.exists():
            raise RuntimeError("certificate generation failed:\n" + result.stderr)
    finally:
        cfg.unlink(missing_ok=True)
    marker.write_text(inputs["domain"], encoding="utf-8")
    print(f"  certificate: created self-signed cert for {', '.join(domains)} (valid 825 days)")


