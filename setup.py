# Docker
# --------------------------------------------------------------------------- #

def docker(*args, capture=False):
    return subprocess.run(["docker", *args], cwd=ROOT, text=True,
                          capture_output=capture)


def docker_available() -> bool:
    if not shutil.which("docker"):
        return False
    return docker("info", capture=True).returncode == 0


def nginx_container_running() -> bool:
    if not COMPOSE_FILE.exists() or not shutil.which("docker"):
        return False
    r = docker("compose", "ps", "--status", "running", "-q", "nginx", capture=True)
    return r.returncode == 0 and bool(r.stdout.strip())


def start_stack() -> bool:
    print("\nStarting containers (first run downloads images)...")
    if docker("compose", "up", "-d", "--remove-orphans").returncode != 0:
        print("! docker compose up failed (see output above).")
        return False

    print("\nValidating config (nginx -t)...")
    test = docker("compose", "exec", "-T", "nginx", "nginx", "-t", capture=True)
    print((test.stdout + test.stderr).strip())
    if test.returncode != 0:
        print("! Config test failed. Fix the inputs and re-run. Logs: docker compose logs nginx")
        return False

    # Apply new config without downtime (no-op if the container was just created).
    docker("compose", "exec", "-T", "nginx", "nginx", "-s", "reload", capture=True)
    return True


def print_summary(inputs: dict, started: bool) -> None:
    host = inputs["domain"].split()[0]
    http_url = f"http://{host}" + ("" if inputs["http_port"] == 80 else f":{inputs['http_port']}")
    https_url = f"https://{host}" + ("" if inputs["https_port"] == 443 else f":{inputs['https_port']}")

    print("\n" + "=" * 64)
    print("NGINX is running." if started else "Files generated.")
    print("=" * 64)
    print(f"  Site          {https_url}   (self-signed cert: use curl -k / accept browser warning)")
    print(f"  HTTP          {http_url}    (redirects to HTTPS)")
    print(f"  Health        {https_url}/healthz")
    print(f"  Stats         {https_url}/nginx_status")
    print(f"  Backends      {', '.join(inputs['backends'])}  [{inputs['protocol']}, least_conn]")
    if host not in ("localhost",) and not is_ip(host):
        print(f"\n  To test locally, add this line to C:\\Windows\\System32\\drivers\\etc\\hosts:")
        print(f"      127.0.0.1  {host}")
    print("\nUseful commands:")
    if inputs["demo"]:
        print(f"  curl -k {https_url}            # run a few times: Hostname rotates app1/app2/app3")
        print("  docker compose stop app2       # simulate a backend failure")
    if not started:
        print("  docker compose up -d           # start")
    print("  docker compose logs -f nginx   # live access log (timings, upstream, cache)")
    print("  python setup.py --from-file    # re-apply after editing nginx-inputs.json")
    print("  docker compose down            # stop everything")


